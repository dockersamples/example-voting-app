#!/usr/bin/env python3
"""Generate k8s/monitoring/prometheusrule.yaml from observability/prometheus/rules/slo.yml.

One source of truth for SLO rules: Docker Compose loads slo.yml directly,
Kubernetes (Prometheus Operator / kube-prometheus-stack) gets the same rules
wrapped in a PrometheusRule. CI fails if the two drift (make check-rules).
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
rules = yaml.safe_load((ROOT / "observability/prometheus/rules/slo.yml").read_text())

doc = {
    "apiVersion": "monitoring.coreos.com/v1",
    "kind": "PrometheusRule",
    "metadata": {
        "name": "vote-slo",
        "namespace": "voting-app",
        "labels": {"release": "kube-prometheus-stack"},
    },
    "spec": {"groups": rules["groups"]},
}

header = "# GENERATED by scripts/gen-k8s-monitoring.py from observability/prometheus/rules/slo.yml. Do not edit.\n"
out = ROOT / "k8s/monitoring/prometheusrule.yaml"
out.write_text(header + yaml.safe_dump(doc, sort_keys=False, width=120))
print(f"wrote {out.relative_to(ROOT)}")
